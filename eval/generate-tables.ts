/**
 * generate-tables.ts — assemble all result JSONs into LaTeX tables for the
 * ACM sigconf paper. Missing inputs degrade to a "(input not available)" note.
 *
 * Run: TS_NODE_PROJECT=eval/tsconfig.json node_modules/.bin/ts-node --transpile-only eval/generate-tables.ts
 * Out: eval/results/paper-tables.md
 */
import * as fs from 'fs';
import * as path from 'path';

const ROOT = path.resolve(__dirname, '..');
const R = (f: string) => path.join(ROOT, 'eval/results', f);
const OUT = R('paper-tables.md');

function load(f: string): any | null {
  try { return JSON.parse(fs.readFileSync(R(f), 'utf8')); } catch { return null; }
}
const n = (v: any, d = '--') => (v === null || v === undefined ? d : v);

const controlled = load('controlled-results.json');
const wild = load('wild-results.json');
const headline = load('headline-stats.json');
const baseline = load('baseline-results.json');
const baselineWild = load('baseline-wild-results.json');

const out: string[] = [];
out.push('# PromptSonar — AISec 2026 Paper Tables', '');
out.push('Generated by `eval/generate-tables.ts`. LaTeX uses `booktabs`; add `\\usepackage{booktabs}`.', '');

/* ---------- Table 1: Controlled corpus results ---------- */
out.push('## Table 1 — Controlled Corpus Results', '');
if (controlled && baseline) {
  const ps = controlled.summary;
  const ss = baseline.summary;
  const rows = [
    ['PromptSonar', ps.cases, ps.findings.TP, ps.findings.FP, ps.findings.FN, ps.precision, ps.recall, ps.f1],
    ['SkillSpector ($\\neg$LLM)', `${ss.comparableCases}$^{a}$`, ss.onComparable.TP, ss.onComparable.FP, ss.onComparable.FN,
      n(ss.onComparable.precision), n(ss.onComparable.recall), n(ss.onComparable.f1)],
    ['SkillSpector (+LLM)', '--', '--', '--', '--', '--', '--', '--'],
  ];
  out.push('```latex');
  out.push('\\begin{table}[t]\\centering\\caption{Controlled corpus: detection accuracy on 22 ground-truthed cases.}\\label{tab:controlled}');
  out.push('\\begin{tabular}{lrrrrrrr}\\toprule');
  out.push('Tool & Cases & TP & FP & FN & Prec. & Rec. & F1 \\\\\\midrule');
  for (const r of rows) out.push(r.join(' & ') + ' \\\\');
  out.push('\\bottomrule\\end{tabular}');
  out.push(`\\\\[2pt]\\footnotesize $^{a}$SkillSpector is skill/file-level; ${ss.outOfScopeCases}/${ps.cases} cases (cross-file, MCP-config, memory) are out of its scope and excluded. (+LLM) not run: ${baseline.summary.skillspectorWithLLM.reason}`);
  out.push('\\end{table}');
  out.push('```', '');
} else out.push('_(controlled-results.json or baseline-results.json not available)_', '');

/* ---------- Table 2: Wild corpus overview ---------- */
out.push('## Table 2 — Wild Corpus Overview', '');
if (wild) {
  const a = wild.aggregate;
  const rows: Array<[string, any]> = [
    ['Repositories scanned', `${a.reposScanned} / ${a.reposListed}`],
    ['Total findings', a.totalFindings],
    ['\\quad critical / high / medium / low', `${a.findingsBySeverity.critical} / ${a.findingsBySeverity.high} / ${a.findingsBySeverity.medium} / ${a.findingsBySeverity.low}`],
    ['\\quad confirmed / probable / potential', `${a.findingsByConfidence.confirmed} / ${a.findingsByConfidence.probable} / ${a.findingsByConfidence.potential}`],
    ['Execution paths', a.totalExecutionPaths],
    ['Cross-file paths', a.totalCrossFilePaths],
    ['Mean / median / max scan time (s)', a.scanSeconds ? `${a.scanSeconds.mean} / ${a.scanSeconds.median} / ${a.scanSeconds.max}` : '--'],
  ];
  out.push('```latex');
  out.push('\\begin{table}[t]\\centering\\caption{Wild corpus: aggregate over 37 public AI repositories.}\\label{tab:wild}');
  out.push('\\begin{tabular}{lr}\\toprule Metric & Value \\\\\\midrule');
  for (const [k, v] of rows) out.push(`${k} & ${v} \\\\`);
  out.push('\\bottomrule\\end{tabular}\\end{table}');
  out.push('```', '');
} else out.push('_(wild-results.json not available)_', '');

/* ---------- Table 3: Headline statistics ---------- */
out.push('## Table 3 — Headline Statistics', '');
if (headline) {
  out.push('```latex');
  out.push('\\begin{table}[t]\\centering\\caption{Share of wild repositories with at least one reachable path to each sensitive action, by confidence tier.}\\label{tab:headline}');
  out.push('\\begin{tabular}{lrrrr}\\toprule');
  out.push('Risk category & \\% repos & Confirmed & Probable & Potential \\\\\\midrule');
  const label: Record<string, string> = { shell_execution: 'Shell execution', filesystem_write: 'Filesystem write', credential_access: 'Credential access', network_external: 'Network / external' };
  for (const c of headline.categories) {
    out.push(`${label[c.risk] || c.risk} & ${c.pctRepos}\\% & ${c.byConfidence.confirmed.pct}\\% & ${c.byConfidence.probable.pct}\\% & ${c.byConfidence.potential.pct}\\% \\\\`);
  }
  out.push('\\midrule');
  out.push(`Cross-file path (per-file--invisible) & ${headline.crossFileOnly.pctRepos}\\% & \\multicolumn{3}{c}{${headline.crossFileOnly.reposWithCrossFilePath}/${headline.reposScanned} repos} \\\\`);
  out.push('\\bottomrule\\end{tabular}\\end{table}');
  out.push('```', '');
} else out.push('_(headline-stats.json not available)_', '');

/* ---------- Table 4: Cross-file detection gap ---------- */
out.push('## Table 4 — Cross-File Detection Gap', '');
if (baselineWild) {
  const repos = (baselineWild.repos || [])
    .filter((r: any) => (r.promptsonar?.crossFilePaths || 0) > 0)
    .sort((a: any, b: any) => (b.promptsonar.crossFilePaths || 0) - (a.promptsonar.crossFilePaths || 0))
    .slice(0, 10);
  out.push('```latex');
  out.push('\\begin{table}[t]\\centering\\caption{Cross-file execution paths found by PromptSonar vs.\\ findings from the per-file baseline (SkillSpector $\\neg$LLM) on the same repositories. SkillSpector has no cross-file path model.}\\label{tab:crossfile}');
  out.push('\\begin{tabular}{lrrr}\\toprule');
  out.push('Repository & PS cross-file & SkillSpector & Gap \\\\\\midrule');
  for (const r of repos) {
    const ps = r.promptsonar.crossFilePaths, ss = r.skillspectorIssues ?? 0;
    out.push(`\\texttt{${String(r.repo).replace(/_/g, '\\_')}} & ${ps} & ${ss} & ${ps} \\\\`);
  }
  const s = baselineWild.summary;
  out.push('\\midrule');
  out.push(`\\textbf{Total} & ${s.crossFileGap.totalPromptsonarCrossFilePaths} & ${s.totalSkillspectorIssues} & ${s.crossFileGap.totalPromptsonarCrossFilePaths} \\\\`);
  out.push('\\bottomrule\\end{tabular}');
  out.push(`\\\\[2pt]\\footnotesize ${s.crossFileGap.note}`);
  out.push('\\end{table}');
  out.push('```', '');
} else out.push('_(baseline-wild-results.json not available)_', '');

/* ---------- Table 5: Scan performance ---------- */
out.push('## Table 5 — Scan Performance', '');
const c5 = controlled?.summary?.timing_s, w5 = wild?.aggregate?.scanSeconds;
if (c5 || w5) {
  out.push('```latex');
  out.push('\\begin{table}[t]\\centering\\caption{Scan performance (seconds). Deterministic, single-threaded, no LLM calls.}\\label{tab:perf}');
  out.push('\\begin{tabular}{lrrrr}\\toprule Corpus & Cases & Mean & Median & Max \\\\\\midrule');
  if (c5) out.push(`Controlled & ${controlled.summary.cases} & ${c5.mean} & ${c5.median} & ${c5.max} \\\\`);
  if (w5) out.push(`Wild & ${wild.aggregate.reposScanned} & ${w5.mean} & ${w5.median} & ${w5.max} \\\\`);
  out.push('\\bottomrule\\end{tabular}\\end{table}');
  out.push('```', '');
} else out.push('_(timing data not available)_', '');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out.join('\n') + '\n');
console.log('Paper tables ->', path.relative(ROOT, OUT));
